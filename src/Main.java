void main() {
    double springCost = 150.00;
    double summerCost = 200.00;
    double fallCost = 175.00;
    double winterCost = 300.00;

    double yearlyCost = springCost + summerCost + fallCost + winterCost;

    System.out.println("Spring maintenance: $" + springCost);
    System.out.println("Summer maintenance: $" + summerCost);
    System.out.println("Fall maintenance: $" + fallCost);
    System.out.println("Winter maintenance: $" + winterCost);
    System.out.println("Total yearly maintenance: $" + yearlyCost);
}